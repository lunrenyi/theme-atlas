import type { SyntaxRole } from './types.ts';

export interface SyntaxToken {
  text: string;
  role?: SyntaxRole;
}

const token = (role: SyntaxRole, text: string): SyntaxToken => ({ role, text });
const text = (value: string): SyntaxToken => ({ text: value });

